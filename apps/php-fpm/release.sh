#!/usr/bin/env bash
# Turn built PHP-FPM 8.3 tarballs into a publishable manifest.
#
#   APP_ORG=Asunano apps/php-fpm/release.sh
#   APP_ORG=Asunano apps/php-fpm/release.sh --from-existing
#
# The manifest checksums and sizes are measured from the files, never typed.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"

BUILD=${BUILD:-sao-r2}
APP_REPO=${APP_REPO:-saopanel-apps}
ARCHES=${ARCHES:-"amd64 arm64"}
DL_BASE=${DL_BASE:-}
URL_BASE=${URL_BASE:-}
DIST=${DIST:-dist}
from_existing=0
allow_partial=0
for arg in "$@"; do
	case "$arg" in
	--from-existing) from_existing=1 ;;
	--allow-partial) allow_partial=1 ;;
	*) echo "release.sh: unknown argument $arg" >&2; exit 2 ;;
	esac
done

[ -n "${APP_ORG:-}" ] || {
	echo "release.sh: APP_ORG is required" >&2
	exit 2
}
if [ "$allow_partial" -eq 0 ]; then
	for arch in amd64 arm64; do
		case " $ARCHES " in
		*" $arch "*) ;;
		*) echo "release.sh: ARCHES=${ARCHES} is missing ${arch}" >&2; exit 2 ;;
		esac
	done
fi

name_of() { echo "php-fpm-${APP_VERSION}-${BUILD}-linux-$1.tar.gz"; }
size_of() { wc -c <"$1" | tr -d ' '; }
sha_of() { sha256sum "$1" | cut -d' ' -f1; }

mkdir -p "$DIST"
if [ "$from_existing" -eq 0 ]; then
	for arch in $ARCHES; do
		echo ">> building ${arch}"
		TARGETARCH="$arch" BUILD="$BUILD" sh apps/php-fpm/build.sh
	done
fi

APP_VERSION=${APP_VERSION:-}
if [ -z "$APP_VERSION" ]; then
	first=
	for arch in $ARCHES; do
		f="$DIST/php-fpm-version-${arch}.txt"
		[ -f "$f" ] || { echo "release.sh: ${f} is missing" >&2; exit 3; }
		v=$(tr -d '[:space:]' <"$f")
		if [ -n "$first" ] && [ "$first" != "$v" ]; then
			echo "release.sh: architecture version mismatch: $first vs $v" >&2
			exit 3
		fi
		first=$v
	done
	APP_VERSION=$first
fi
case "$APP_VERSION" in
8.3.*) ;;
*) echo "release.sh: expected a PHP 8.3 version, got $APP_VERSION" >&2; exit 3 ;;
esac

for arch in $ARCHES; do
	f="$DIST/$(name_of "$arch")"
	[ -f "$f" ] || { echo "release.sh: ${f} is missing" >&2; exit 3; }
	tar tzf "$f" >/dev/null || { echo "release.sh: ${f} is not a tarball" >&2; exit 3; }
done

TAG="php-fpm-v${APP_VERSION}-${BUILD}"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
: >"$work/artefacts.yaml"
for arch in $ARCHES; do
	f="$DIST/$(name_of "$arch")"
	if [ -n "$URL_BASE" ]; then
		url="${URL_BASE%/}/$(name_of "$arch")"
	else
		url="https://github.com/${APP_ORG}/${APP_REPO}/releases/download/${TAG}/$(name_of "$arch")"
	fi
	{
		echo "    - arch: ${arch}"
		echo "      url: ${url}"
		echo "      sha256: \"$(sha_of "$f")\""
		echo "      size: $(size_of "$f")"
	} >>"$work/artefacts.yaml"
done

: >"$work/mirrors.yaml"
if [ -z "$URL_BASE" ]; then
	echo "    - https://gh-proxy.com/https://github.com/${APP_ORG}/${APP_REPO}/releases/download/${TAG}/" >>"$work/mirrors.yaml"
	if [ -n "$DL_BASE" ]; then
		echo "    - ${DL_BASE%/}/apps/php-fpm/${APP_VERSION}-${BUILD}/" >>"$work/mirrors.yaml"
	fi
fi

out="$DIST/apps/php-fpm.yaml"
mkdir -p "$DIST/apps"
sed -n '/^id:/,$p' apps/php-fpm/manifest.yaml.tmpl >"$work/body.yaml"
{
	echo "# Generated by apps/php-fpm/release.sh from apps/php-fpm/manifest.yaml.tmpl."
	echo "# Do not edit: the next release replaces this file."
	sed -e "s|<version>|${APP_VERSION}|g" \
		-e "s|<build>|${BUILD}|g" \
		-e "s|<org>|${APP_ORG}|g" \
		-e "/^<artefacts>\$/r $work/artefacts.yaml" -e "/^<artefacts>\$/d" \
		-e "/^<mirrors>\$/r $work/mirrors.yaml" -e "/^<mirrors>\$/d" \
		"$work/body.yaml"
} >"$out"

if [ ! -s "$work/mirrors.yaml" ]; then
	sed -i 's/^  mirrors:$/  mirrors: []/' "$out"
fi
if grep -nE '<[a-z]+>' "$out"; then
	echo "release.sh: ${out} still contains a placeholder" >&2
	exit 4
fi
for arch in $ARCHES; do
	grep -q -- "-linux-${arch}.tar.gz" "$out" || {
		echo "release.sh: ${out} does not mention ${arch}" >&2
		exit 4
	}
done

(cd "$DIST" && sha256sum php-fpm-*-linux-*.tar.gz >SHA256SUMS)
(cd "$DIST" && sha256sum -c SHA256SUMS)

echo
echo ">> release ${TAG}"
ls -lh "$DIST"/php-fpm-*-linux-*.tar.gz "$out" | awk '{printf "   %-62s %s\n", $9, $5}'
echo
cat "$DIST/SHA256SUMS"
echo
cat "$out"

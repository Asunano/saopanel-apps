#!/usr/bin/env bash
# Turn built phpMyAdmin tarballs into a publishable Web App manifest.
#
#   APP_ORG=Asunano apps/phpmyadmin/release.sh
#   APP_ORG=Asunano URL_BASE=https://saopanel.losn.cc/apps/phpmyadmin/5.2.2-sao-r1 \
#     apps/phpmyadmin/release.sh --from-existing
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"

APP_VERSION=${APP_VERSION:-5.2.2}
BUILD=${BUILD:-sao-r1}
APP_REPO=${APP_REPO:-saopanel-apps}
ARCHES=${ARCHES:-"amd64 arm64"}
URL_BASE=${URL_BASE:-}
DL_BASE=${DL_BASE:-}
DIST=${DIST:-dist}
from_existing=0
for arg in "$@"; do
	case "$arg" in
	--from-existing) from_existing=1 ;;
	*) echo "release.sh: unknown argument $arg" >&2; exit 2 ;;
	esac
done

for arch in $ARCHES; do
	[ "$arch" = amd64 ] || [ "$arch" = arm64 ] || {
		echo "release.sh: unknown architecture $arch" >&2
		exit 2
	}
done

name_of() { echo "phpmyadmin-${APP_VERSION}-${BUILD}-linux-$1.tar.gz"; }
size_of() { wc -c <"$1" | tr -d ' '; }
sha_of() { sha256sum "$1" | cut -d' ' -f1; }
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

mkdir -p "$DIST"
if [ "$from_existing" -eq 0 ]; then
	for arch in $ARCHES; do
		echo ">> building ${arch}"
		TARGETARCH="$arch" VERSION="$APP_VERSION" BUILD="$BUILD" \
			DIST_DIR="$ROOT/$DIST" sh apps/phpmyadmin/build.sh
	done
fi

for arch in $ARCHES; do
	f="$DIST/$(name_of "$arch")"
	[ -f "$f" ] || { echo "release.sh: ${f} is missing" >&2; exit 3; }
	tar tzf "$f" >/dev/null || { echo "release.sh: ${f} is not a tarball" >&2; exit 3; }
	tar tzf "$f" >"$work/list-${arch}" || { echo "release.sh: ${f} is not a tarball" >&2; exit 3; }
	grep -qx 'payload/index.php' "$work/list-${arch}" || {
		echo "release.sh: ${f} has no payload/index.php" >&2
		exit 3
	}
done

TAG="phpmyadmin-v${APP_VERSION}-${BUILD}"
: >"$work/artefacts.yaml"
for arch in $ARCHES; do
	f="$DIST/$(name_of "$arch")"
	if [ -n "$URL_BASE" ]; then
		url="${URL_BASE%/}/$(name_of "$arch")"
	else
		url="https://github.com/${APP_ORG:-Asunano}/${APP_REPO}/releases/download/${TAG}/$(name_of "$arch")"
	fi
	{
		echo "    - arch: ${arch}"
		echo "      url: ${url}"
		echo "      sha256: \"$(sha_of "$f")\""
		echo "      size: $(size_of "$f")"
	} >>"$work/artefacts.yaml"
done

: >"$work/mirrors.yaml"
if [ -z "$URL_BASE" ]; then
	echo "    - https://gh-proxy.com/https://github.com/Asunano/${APP_REPO}/releases/download/${TAG}/" >>"$work/mirrors.yaml"
	if [ -n "$DL_BASE" ]; then
		echo "    - ${DL_BASE%/}/apps/phpmyadmin/${APP_VERSION}-${BUILD}/" >>"$work/mirrors.yaml"
	fi
fi

out="$DIST/apps/phpmyadmin.yaml"
mkdir -p "$DIST/apps"
sed -n '/^id:/,$p' apps/phpmyadmin/manifest.yaml.tmpl >"$work/body.yaml"
{
	echo "# Generated by apps/phpmyadmin/release.sh from apps/phpmyadmin/manifest.yaml.tmpl."
	echo "# Do not edit: the next release replaces this file."
	sed -e "s|<version>|${APP_VERSION}|g" \
		-e "s|<build>|${BUILD}|g" \
		-e "/^<artefacts>\$/r $work/artefacts.yaml" -e "/^<artefacts>\$/d" \
		-e "/^<mirrors>\$/r $work/mirrors.yaml" -e "/^<mirrors>\$/d" \
		"$work/body.yaml"
} >"$out"

if [ ! -s "$work/mirrors.yaml" ]; then
	sed -i 's/^  mirrors:$/  mirrors: []/' "$out"
fi
if grep -nE '<[a-z]+>' "$out"; then
	echo "release.sh: ${out} still contains a placeholder" >&2
	exit 4
fi
for arch in $ARCHES; do
	grep -q -- "-linux-${arch}.tar.gz" "$out" || {
		echo "release.sh: ${out} does not mention ${arch}" >&2
		exit 4
	}
done

(cd "$DIST" && sha256sum phpmyadmin-*-linux-*.tar.gz >SHA256SUMS.phpmyadmin)
(cd "$DIST" && sha256sum -c SHA256SUMS.phpmyadmin)

echo
echo ">> release ${TAG}"
ls -lh "$DIST"/phpmyadmin-*-linux-*.tar.gz "$out" | awk '{printf "   %-62s %s\n", $9, $5}'
echo
cat "$DIST/SHA256SUMS.phpmyadmin"
echo
cat "$out"


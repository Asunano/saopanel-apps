#!/bin/sh
# Build the phpMyAdmin Web App package. The payload is architecture
# independent; the artefact name carries the target architecture so the app
# store's manifest shape stays the same as a native package.
set -eu

VERSION=${VERSION:-5.2.2}
BUILD=${BUILD:-sao-r1}
ARCH=${TARGETARCH:-$(uname -m)}
DIST_DIR=${DIST_DIR:-/w/dist}
case "$ARCH" in
amd64 | arm64) ;;
*)
	echo "build.sh: unsupported architecture $ARCH" >&2
	exit 2
	;;
esac

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
archive="$work/phpmyadmin.tar.gz"
base="https://files.phpmyadmin.net/phpMyAdmin/${VERSION}"
name="phpMyAdmin-${VERSION}-all-languages"

echo ">> phpMyAdmin ${VERSION}, ${ARCH}"
curl -fsSL --retry 3 -o "$archive" "$base/${name}.tar.gz"
if [ -n "${PHPMYADMIN_SHA256:-}" ]; then
	want=$PHPMYADMIN_SHA256
else
	curl -fsSL --retry 3 -o "$archive.sha256" "$base/${name}.tar.gz.sha256"
	want=$(cut -d' ' -f1 <"$archive.sha256")
fi
got=$(sha256sum "$archive" | cut -d' ' -f1)
[ -n "$want" ] || {
	echo "build.sh: no phpMyAdmin checksum" >&2
	exit 3
}
[ "$got" = "$want" ] || {
	echo "build.sh: checksum mismatch: $got, want $want" >&2
	exit 3
}

stage="$work/stage"
mkdir -p "$stage/payload"
tar -xzf "$archive" -C "$work"
src="$work/$name"
[ -d "$src" ] || {
	echo "build.sh: archive did not contain $name" >&2
	exit 3
}
cp -a "$src"/. "$stage/payload/"
# The setup wizard is an unauthenticated configuration surface. The panel
# renders config.inc.php itself, so it is never shipped either.
rm -rf "$stage/payload/setup" "$stage/payload/config.inc.php" "$stage/payload/.git"

# The config template the panel fills at install time. The blowfish secret is
# the one value that must not be in this tarball: every install gets its own.
mkdir -p "$stage/conf"
cat >"$stage/conf/config.inc.php.tmpl" <<'PHP'
<?php
// Generated by saopanel at install time. Do not edit: the next install replaces
// it, and the blowfish secret in it belongs to this machine.
$cfg['blowfish_secret'] = '{{blowfish_secret}}';

$i = 0;
$i++;
$cfg['Servers'][$i]['auth_type'] = 'cookie';
$cfg['Servers'][$i]['host'] = '127.0.0.1';
$cfg['Servers'][$i]['compress'] = false;
$cfg['Servers'][$i]['AllowNoPassword'] = false;
PHP

# The server block nginx includes. 8081 is the port the manifest declares and the
# panel turns into a link, so the two must agree.
mkdir -p "$stage/conf/nginx"
cat >"$stage/conf/nginx/phpmyadmin.conf" <<'CONF'
# Served by the panel's nginx, installed from the app store.
# The payload lives at the default root's apps tree; the manager runs as
# www-php, which owns that tree.
server {
    listen 8081;
    root /opt/saopanel/apps/phpmyadmin/current/payload;
    index index.php;

    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }
    location ~ \.php$ {
        fastcgi_pass unix:/run/saopanel/php/php-fpm83.sock;
        fastcgi_index index.php;
        include fastcgi_params;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
    }
    location ~ /\.(?!well-known) {
        deny all;
    }
}
CONF

cat >"$stage/manifest.json" <<JSON
{"id":"phpmyadmin","name":"phpMyAdmin","version":"${VERSION}","build":"${BUILD}","arch":"${ARCH}","kind":"files","php":"8.3"}
JSON

out="phpmyadmin-${VERSION}-${BUILD}-linux-${ARCH}.tar.gz"
mkdir -p "$DIST_DIR"
tar -C "$stage" -czf "$DIST_DIR/$out" payload conf manifest.json
printf '%s\n' "$VERSION" >"$DIST_DIR/phpmyadmin-version-${ARCH}.txt"
(cd "$DIST_DIR" && { grep -v "  ${out}\$" SHA256SUMS 2>/dev/null || true; sha256sum "$out"; } >SHA256SUMS.new && mv SHA256SUMS.new SHA256SUMS)
echo ">> artefact: $DIST_DIR/$out"
ls -lh "$DIST_DIR/$out"

